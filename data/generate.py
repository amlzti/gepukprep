"""
GepukPrep AI - dataset builder.

The dataset is the 30-day "Simulated Daily Sales" table from the group's report (Section 3.4),
21 Nov - 20 Dec 2026, following the UTP September 2026 academic calendar.

  portions = round(117 x period multiplier x weekend multiplier x rain multiplier + noise)
  baseline 117 | weekend (Sat-Sun) x1.24 | rain x0.85 | study break x0.95 | exam week x0.75
  semester break x0.40 | noise +/- 5 (fixed values from the report)

The semester-break rows are recalculated with x0.40, as stated in the report text
(the printed table had used x0.50). Rainy days are the report's own choices, not real weather.
Public holidays: none in this period; the report sets no holiday multiplier.

Run:  python3 generate.py     (writes sales.csv and sales.js)
"""
import csv, json
from datetime import date
from pathlib import Path

HERE = Path(__file__).parent
BASELINE, WEEKEND, RAIN = 117, 1.24, 0.85
PERIOD = {"Lecture": 1.00, "Study break": 0.95, "Exams": 0.75, "Break": 0.40}

# date, period, rain (Y/N), noise  -- from the report, Section 3.4
REPORT = [
    ("2026-11-21", "Lecture", "N", 0), ("2026-11-22", "Lecture", "N", -3), ("2026-11-23", "Lecture", "N", 1),
    ("2026-11-24", "Lecture", "Y", 5), ("2026-11-25", "Lecture", "N", -5), ("2026-11-26", "Lecture", "N", -4),
    ("2026-11-27", "Lecture", "N", 3), ("2026-11-28", "Study break", "N", -4), ("2026-11-29", "Study break", "Y", 0),
    ("2026-11-30", "Study break", "Y", 4), ("2026-12-01", "Study break", "N", -5), ("2026-12-02", "Study break", "N", 3),
    ("2026-12-03", "Exams", "N", -2), ("2026-12-04", "Exams", "N", -5), ("2026-12-05", "Exams", "N", -4),
    ("2026-12-06", "Exams", "Y", 1), ("2026-12-07", "Exams", "N", 1), ("2026-12-08", "Exams", "Y", -4),
    ("2026-12-09", "Exams", "N", -2), ("2026-12-10", "Exams", "N", -4), ("2026-12-11", "Exams", "Y", 3),
    ("2026-12-12", "Exams", "N", 1), ("2026-12-13", "Exams", "N", -5), ("2026-12-14", "Exams", "N", 4),
    ("2026-12-15", "Exams", "N", -4), ("2026-12-16", "Break", "N", -2), ("2026-12-17", "Break", "Y", 5),
    ("2026-12-18", "Break", "N", 5), ("2026-12-19", "Break", "N", 4), ("2026-12-20", "Break", "N", -5),
]


def excel_round(x):            # Excel's ROUND: halves go away from zero
    return int(x + 0.5) if x >= 0 else -int(-x + 0.5)


def main():
    cal = json.loads((HERE / "calendar.json").read_text())
    rows = []
    for iso, period, rain, noise in REPORT:
        d = date.fromisoformat(iso)
        weekend = d.weekday() >= 5
        mult = PERIOD[period] * (WEEKEND if weekend else 1) * (RAIN if rain == "Y" else 1)
        rows.append({
            "date": iso, "dow": d.strftime("%a"), "holiday": 0, "holiday_name": "",
            "rain_mm": "", "weather": "Rainy" if rain == "Y" else "Dry", "utp_status": period,
            "noise": noise, "portions_sold": excel_round(BASELINE * mult + noise),
            "owner_planned": "", "leftover_portions": "", "sold_out": 0, "source": "simulated",
        })
    with open(HERE / "sales.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    (HERE / "sales.js").write_text(
        "// Generated by data/generate.py - do not edit by hand.\n"
        f"window.GEPUK_CALENDAR = {json.dumps(cal)};\n"
        "window.GEPUK_FORECAST = null;\n"
        f"window.GEPUK_DATA = {json.dumps(rows)};\n")
    print(len(rows), "days:", [r["portions_sold"] for r in rows], "total", sum(r["portions_sold"] for r in rows))


if __name__ == "__main__":
    main()
